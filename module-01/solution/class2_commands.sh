#!/usr/bin/env bash
# ক্লাস ২ — ল্যাবের সমাধান
#
# এটা চালানোর জন্য না, পড়ার জন্য। এক একটা কমান্ড নিজে টাইপ করে দেখুন।
# repo-র মূল ফোল্ডার থেকে চালাবেন।

LOG=module-01/data/app_2026-10.log

# ---------------------------------------------------------------
# ০. আগে ফাইলটার সাথে পরিচয়
# ---------------------------------------------------------------

ls -lh $LOG                 # সাইজ কত
wc -l $LOG                  # কয়টা লাইন
head -3 $LOG                # উপরের তিনটা লাইন — গড়নটা দেখে নিন
tail -3 $LOG                # নিচের তিনটা

# গড়নটা এরকম, চারটা অংশ, মাঝখানে পাইপ চিহ্ন:
# 2026-10-01 00:00:12 | WARN  | ingest.api      | partial page returned, 7 of 50 records
#         তারিখ+সময়      level     component                   বার্তা


# ---------------------------------------------------------------
# ১. মোট কয়টা ERROR
# ---------------------------------------------------------------

# প্রথম চেষ্টা — আর এটাই ফাঁদ
grep -c "ERROR" $LOG
# 4887

# কেন বেশি? কারণ কিছু WARN লাইনের বার্তার ভেতরেও ERROR_CODE লেখা আছে
grep "ERROR" $LOG | grep -v "| ERROR |" | head -3

# ঠিক উত্তর — level-এর ঘরটা ধরে খোঁজা
grep -c "| ERROR |" $LOG
# 4827


# ---------------------------------------------------------------
# ২. তারিখ অনুযায়ী কয়টা করে ERROR
# ---------------------------------------------------------------

# ধাপে ধাপে বানানো — প্রতিটা ধাপ আলাদা করে চালিয়ে দেখুন

grep "| ERROR |" $LOG | head -3                    # শুধু ERROR লাইনগুলো
grep "| ERROR |" $LOG | cut -c1-10 | head -3       # প্রতিটা লাইনের প্রথম ১০ অক্ষর = তারিখ
grep "| ERROR |" $LOG | cut -c1-10 | sort | head -3  # সাজানো (uniq-এর আগে লাগবেই)

# পুরোটা একসাথে
grep "| ERROR |" $LOG | cut -c1-10 | sort | uniq -c

# বেশি থেকে কম ক্রমে
grep "| ERROR |" $LOG | cut -c1-10 | sort | uniq -c | sort -rn | head -5
#  781 2026-10-17     <- এই দিনটায় কিছু একটা হয়েছিল
#  264 2026-10-19
#  243 2026-10-18
#  168 2026-10-13
#  166 2026-10-14


# ---------------------------------------------------------------
# ৩. ফলটা একটা নতুন ফাইলে লিখুন
# ---------------------------------------------------------------

grep "| ERROR |" $LOG | cut -c1-10 | sort | uniq -c > errors_by_date.txt
cat errors_by_date.txt | head -5

# >  মানে নতুন করে লেখো (আগের লেখা মুছে যাবে)
# >> মানে শেষে যোগ করো

{
  echo "ThelaGari pipeline — October 2026"
  echo "তারিখ অনুযায়ী ERROR"
  grep "| ERROR |" $LOG | cut -c1-10 | sort | uniq -c
} > error_report.txt


# ---------------------------------------------------------------
# বোনাস
# ---------------------------------------------------------------

# ক. কোন component-এ সবচেয়ে বেশি ERROR
grep "| ERROR |" $LOG | cut -d'|' -f3 | tr -d ' ' | sort | uniq -c | sort -rn
# 1308 ingest.api
#  998 transform
#  956 loader
#  691 ingest.scraper
#  632 scheduler
#  242 auth

# cut -d'|' -f3  মানে: পাইপ চিহ্ন দিয়ে ভাগ করো, তৃতীয় টুকরোটা নাও
# tr -d ' '      মানে: ফাঁকা জায়গাগুলো মুছে দাও

# খ. পুরো ফাইলে level-এর হিসাব
cut -d'|' -f2 $LOG | tr -d ' ' | sort | uniq -c | sort -rn
# 78306 INFO
# 12884 WARN
#  4827 ERROR
#  3983 DEBUG

# গ. ১৭ তারিখে কী হয়েছিল — সবচেয়ে বেশি কোন বার্তাটা
grep "^2026-10-17" $LOG | grep "| ERROR |" | cut -d'|' -f4 | sort | uniq -c | sort -rn | head -5

# ঘ. ১৭ তারিখের ERROR কোন ঘণ্টায় বেশি
grep "^2026-10-17" $LOG | grep "| ERROR |" | cut -c12-13 | sort | uniq -c

# ঙ. শুধু ১৭ তারিখের ERROR আলাদা ফাইলে
grep "^2026-10-17" $LOG | grep "| ERROR |" > incident_17oct.log
wc -l incident_17oct.log


# ---------------------------------------------------------------
# যে ভুলগুলো সবচেয়ে বেশি হয়
# ---------------------------------------------------------------

# sort ছাড়া uniq — uniq শুধু পাশাপাশি একই লাইন গোনে, তাই আগে sort লাগবেই
# grep "| ERROR |" $LOG | cut -c1-10 | uniq -c        <- ভুল ফল দেবে

# sort -rn আর sort -r আলাদা
#   sort -r   অক্ষর ধরে উল্টো ক্রমে  →  "9" কে "100"-এর উপরে রাখে
#   sort -rn  সংখ্যা ধরে উল্টো ক্রমে →  এটাই চাই

# cat দিয়ে শুরু করার দরকার নেই
#   cat $LOG | grep ERROR        <- চলে, কিন্তু বাড়তি
#   grep ERROR $LOG              <- এটাই যথেষ্ট
